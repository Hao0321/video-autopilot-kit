TRANSFORM_WORKER = r"""
import json, sys
from pathlib import Path
from sync_canonical import _transform
from public_privacy_sanitizer import sanitize_public_text
result = {}
for relative, text in json.load(sys.stdin).items():
    try:
        result[relative] = sanitize_public_text(relative, _transform(text, Path(relative).name))
    except Exception:  # noqa: BLE001 - the caller falls back to the raw base text
        result[relative] = None
json.dump(result, sys.stdout, ensure_ascii=False)
"""
BLOCKERS = ("CONFLICT", "ERROR")


@dataclass(frozen=True)
class Target:
    kind: str
    root: str = ""
    relative: str = ""
    note: str = ""


@dataclass(frozen=True)
class TextStyle:
    bom: bool = False
    crlf: bool = False


@dataclass
class Item:
    target: Target
    sources: list = field(default_factory=list)
    status: str = "SKIPPED"
    detail: str = ""
    result: object = None
    style: TextStyle = TextStyle()
    conflicts: int = 0

    def row(self) -> dict:
        return {
            "status": self.status, "kind": self.target.kind,
            "public": self.sources, "root": self.target.root,
            "canonical": self.target.relative, "detail": self.detail,
            "conflicts": self.conflicts,
        }


def classify(relative: str) -> Target:
    """Map one public path to its canonical source, or explain why none."""
    if relative in GENERATED:
        return Target("generated", note=GENERATED[relative])
    if relative in PROJECTIONS:
        return Target("projection", note=PROJECTIONS[relative])
    if relative in PUBLIC_OWNED_PATHS:
        return Target("public-owned", note="owned by the public kit; nothing to backport")
    for prefix, names, root, canonical_prefix in GROUPS:
        if relative.startswith(prefix) and relative[len(prefix):] in names:
            leaf = relative[len(prefix):]
            return Target("derived", root, canonical_prefix + leaf, REVIEW_NOTES.get(relative, ""))
    return Target("repo-native", note="lives only in the public kit")


def decode(payload: bytes) -> tuple:
    bom = payload.startswith(b"\xef\xbb\xbf")
    text = payload.decode("utf-8-sig")
    crlf = "\r\n" in text
    return text.replace("\r\n", "\n").replace("\r", "\n"), TextStyle(bom, crlf)


def encode(text: str, style: TextStyle) -> bytes:
    if style.crlf:
        text = text.replace("\n", "\r\n")
    data = text.encode("utf-8")
    return b"\xef\xbb\xbf" + data if style.bom else data


def _git(repository: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=str(repository), capture_output=True, check=check)


def changed_paths(repository: Path, base: str, head: str) -> list:
    raw = _git(repository, "diff", "--name-only", "--no-renames", "-z", base, head).stdout
    return sorted(part for part in raw.decode("utf-8").split("\0") if part)


def blob(repository: Path, ref: str, relative: str):
    result = _git(repository, "show", "%s:%s" % (ref, relative), check=False)
    return decode(result.stdout)[0] if result.returncode == 0 else None


def _transform_with(scripts: Path, texts: dict) -> dict:
    """Run the public transform pipeline of one scripts/ tree over ``texts``."""
    env = dict(os.environ, PYTHONUTF8="1", PYTHONDONTWRITEBYTECODE="1")
    result = subprocess.run([sys.executable, "-c", TRANSFORM_WORKER], cwd=str(scripts),
                            input=json.dumps(texts).encode("utf-8"), capture_output=True, env=env)
    if result.returncode:
        return {}
    return json.loads(result.stdout.decode("utf-8"))


class ScriptTrees:
    """Extract scripts/ of any commit once, so every replay step uses its own rules."""

    def __init__(self, repository: Path) -> None:
        self.repository = repository
        self._temp = tempfile.TemporaryDirectory(prefix="canonical-backport-scripts-")
        self._trees: dict = {}

    def __enter__(self) -> "ScriptTrees":
        return self

    def __exit__(self, *_exc) -> None:
        self._temp.cleanup()

    def at(self, ref: str) -> Path:
        commit = _git(self.repository, "rev-parse", ref).stdout.decode("ascii").strip()
        if commit not in self._trees:
            tree = Path(self._temp.name) / commit
            tree.mkdir()
            names = _git(self.repository, "ls-tree", "--name-only", commit, "scripts/").stdout
            for name in names.decode("utf-8").split():
                if name.endswith(".py"):
                    payload = _git(self.repository, "show", "%s:%s" % (commit, name)).stdout
                    (tree / Path(name).name).write_bytes(payload)
            self._trees[commit] = tree
        return self._trees[commit]


def transform_adjusted_bases(repository: Path, base: str, head: str, bases: dict,
                             scripts: ScriptTrees) -> dict:
    """Fold transform-rule changes into the merge base so they stay public-only.

    For each base text B the base and head pipelines give Tb and Th; merging
    B with base Tb and other Th applies exactly the rewrites the head rules
    add.  Non-idempotent legacy rules cancel out because both sides share them.
    """
    if not TRANSFORM_SCRIPTS & set(changed_paths(repository, base, head)) or not bases:
        return dict(bases)
    before = _transform_with(scripts.at(base), bases)
    after = _transform_with(scripts.at(head), bases)
    adjusted = {}
    for relative, text in bases.items():
        old, new = before.get(relative), after.get(relative)
        if old is None or new is None or old == new:
            adjusted[relative] = text
            continue
        merged, conflicts = merge3(text, old, new)
        adjusted[relative] = text if conflicts else merged
    return adjusted


def merge3(current: str, base: str, other: str) -> tuple:
    """Return (merged LF text, conflict count) from ``git merge-file``."""
    with tempfile.TemporaryDirectory(prefix="canonical-backport-") as temp:
        paths = []
        for name, text in (("canonical", current), ("public-base", base), ("public-head", other)):
            path = Path(temp) / name
            path.write_bytes(text.encode("utf-8"))
            paths.append(str(path))
        labels = ("-L", "canonical", "-L", "public-base", "-L", "public-head")
        result = subprocess.run(
            ["git", "merge-file", "-p", "--diff3", *labels, *paths], capture_output=True
        )
    if result.returncode > 127:
        raise RuntimeError("git merge-file failed: " + result.stderr.decode("utf-8", "replace"))
    return result.stdout.decode("utf-8"), result.returncode


def decide(item: Item, base, head, current) -> None:
    """Fill status/result for one canonical file from public base/head texts."""
    if current is None:
        if base is None and head is not None:
            item.status, item.result = "CREATE", head
        elif head is None:
            item.status = "ALREADY_APPLIED"
        else:
            item.status, item.detail = "ERROR", "canonical file is missing"
        return
    text, item.style = decode(current)
    if head is None:
        item.status = "DELETE" if text == base else "CONFLICT"
        item.detail = "" if text == base else "canonical diverged from the deleted public base"
    elif text == head:
        item.status = "ALREADY_APPLIED"
    elif base is None:
        item.status, item.detail = "CONFLICT", "canonical already has a different file"
    elif text == base:
        item.status, item.result = "FAST_FORWARD", head
    else:
        item.result, item.conflicts = merge3(text, base, head)
        if item.conflicts:
            item.status = "CONFLICT"
        else:
            item.status = "ALREADY_APPLIED" if item.result == text else "MERGED"


def public_paths_for(root_key: str, canonical_relative: str) -> list:
    """Return every public output generated from one canonical file."""
    paths = []
    for prefix, names, root, canonical_prefix in GROUPS:
        if root == root_key and canonical_relative.startswith(canonical_prefix):
            if canonical_relative[len(canonical_prefix):] in names:
                paths.append(prefix + canonical_relative[len(canonical_prefix):])
    return paths


def _plan_target(repository: Path, base: str, head: str, item: Item, view: "CanonicalView",
                 bases: dict, projected: dict) -> None:
    members = public_paths_for(item.target.root, item.target.relative)
    versions = {(bases.get(name, blob(repository, base, name)), blob(repository, head, name))
                for name in members}
    if len(versions) != 1:
        item.status, item.detail = "ERROR", "mirrored public copies differ: " + ", ".join(members)
        return
    if view.roots.get(item.target.root) is None:
        item.detail = "pass %s to backport this file" % ROOT_FLAGS[item.target.root]
        return
    (base_text, head_text), = versions
    if head_text is not None and projected.get(item.sources[0]) == head_text:
        # The head sync pipeline already turns this canonical file into the
        # public head: the change was public-only (a transform or sanitizer).
        item.status, item.detail = "ALREADY_APPLIED", "head transforms reproduce it from the canonical"
        return
    try:
        decide(item, base_text, head_text, view.read(item.target))
    except (UnicodeDecodeError, RuntimeError) as exc:
        item.status, item.detail = "ERROR", str(exc)
        return
    if item.target.note and item.status in WRITES:
        item.detail = "review: " + item.target.note


class CanonicalView:
    """Canonical files as seen by a replay: disk contents plus earlier steps."""

    def __init__(self, roots: dict) -> None:
        self.roots = roots
        self.changed: dict = {}

    def disk(self, target: Target):
        root = self.roots.get(target.root)
        path = Path(root) / target.relative if root is not None else None
        return path.read_bytes() if path is not None and path.is_file() else None

    def read(self, target: Target):
        key = (target.root, target.relative)
        return self.changed[key] if key in self.changed else self.disk(target)

    def record(self, item: Item) -> None:
        payload = None if item.status == "DELETE" else encode(item.result, item.style)
        self.changed[(item.target.root, item.target.relative)] = payload


def plan(repository: Path, base: str, head: str, roots: dict,
         view: CanonicalView | None = None, scripts: ScriptTrees | None = None) -> list:
    """Classify every changed public path and plan its canonical effect (one step)."""
    if scripts is None:
        with ScriptTrees(repository) as trees:
            return plan(repository, base, head, roots, view, trees)
    view = view if view is not None else CanonicalView(roots)
    grouped: dict = {}
    items = []
    for relative in changed_paths(repository, base, head):
        target = classify(relative)
        if target.kind != "derived":
            items.append(Item(target, [relative], "SKIPPED", target.note))
        else:
            grouped.setdefault((target.root, target.relative), Item(target)).sources.append(relative)
    raw = {name: blob(repository, base, name) for item in grouped.values()
           for name in public_paths_for(item.target.root, item.target.relative)}
    bases = transform_adjusted_bases(repository, base, head,
                                     {name: text for name, text in raw.items() if text is not None},
                                     scripts)
    projected = _project_canonical(grouped.values(), view, scripts.at(head))
    for key in sorted(grouped):
        item = grouped[key]
        _plan_target(repository, base, head, item, view, bases, projected)
        items.append(item)
    return items


def _project_canonical(items, view: CanonicalView, scripts: Path) -> dict:
    """Run the head sync transforms over the (replayed) canonical files."""
    texts = {}
    for item in items:
        payload = view.read(item.target)
        if payload is not None:
            try:
                texts[item.sources[0]] = decode(payload)[0]
            except UnicodeDecodeError:
                continue
    return _transform_with(scripts, texts) if texts else {}


def _first_parent_commits(repository: Path, base: str, head: str) -> list:
    raw = _git(repository, "rev-list", "--reverse", "--first-parent", "%s..%s" % (base, head)).stdout
    return raw.decode("ascii").split()


def replay(repository: Path, base: str, head: str, roots: dict) -> list:
    """Replay base..head one first-parent commit at a time on a virtual canonical.

    A content edit committed before a public-only rewrite of the same line then
    merges cleanly, because each step sees exactly one kind of change.
    """
    view, final, blocked, skipped, merged = CanonicalView(roots), {}, set(), {}, set()
    with ScriptTrees(repository) as scripts:
        settled = _already_at_head(repository, base, head, view, scripts)
        final.update(settled)
        previous = base
        for commit in _first_parent_commits(repository, base, head):
            for item in plan(repository, previous, commit, roots, view, scripts):
                key = (item.target.root, item.target.relative)
                if item.target.kind != "derived":
                    skipped.setdefault(item.sources[0], item)
                    continue
                if key in blocked or key in settled:
                    continue
                final[key] = _merge_sources(final.get(key), item)
                if item.status in BLOCKERS:
                    item.detail = ("%s (at %s)" % (item.detail, commit[:10])).strip()
                    blocked.add(key)
                elif item.status in WRITES:
                    view.record(item)
                    if item.status == "MERGED":
                        merged.add(key)
            previous = commit
    return [_settle(item, view, blocked, key in merged) for key, item in sorted(final.items())] + \
        [skipped[name] for name in sorted(skipped)]


def _already_at_head(repository: Path, base: str, head: str, view: CanonicalView,
                     scripts: ScriptTrees) -> dict:
    """Files whose canonical already publishes as the head need no replay (re-runs)."""
    targets: dict = {}
    for relative in changed_paths(repository, base, head):
        target = classify(relative)
        if target.kind == "derived" and view.roots.get(target.root) is not None:
            targets.setdefault((target.root, target.relative), Item(target)).sources.append(relative)
    projected = _project_canonical(targets.values(), view, scripts.at(head))
    settled = {}
    for key, item in targets.items():
        heads = {blob(repository, head, source) for source in item.sources}
        if len(heads) != 1:
            continue  # diverged mirrors: let the replay report the ERROR
        head_text, present = heads.pop(), view.read(item.target)
        if head_text is None and present is None:
            item.status = "ALREADY_APPLIED"
        elif head_text is not None and projected.get(item.sources[0]) == head_text:
            item.status, item.detail = "ALREADY_APPLIED", "canonical already publishes as the head"
        else:
            continue
        settled[key] = item
    return settled


def _merge_sources(previous, item: Item) -> Item:
    if previous is not None:
        item.sources = sorted(set(previous.sources) | set(item.sources))
    return item


def _settle(item: Item, view: CanonicalView, blocked: set, merged: bool) -> Item:
    """Turn the replayed view into one final instruction per canonical file."""
    if (item.target.root, item.target.relative) in blocked or item.status == "SKIPPED":
        return item
    final, disk = view.read(item.target), view.disk(item.target)
    if final == disk:
        item.status, item.result = "ALREADY_APPLIED", None
    elif final is None:
        item.status, item.result = "DELETE", None
    else:
        item.result, item.style = decode(final)
        item.status = "CREATE" if disk is None else ("MERGED" if merged else "FAST_FORWARD")
    return item


def _atomic_write(path: Path, payload: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temp = tempfile.mkstemp(prefix="." + path.name + ".", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(handle, "wb") as stream:
            stream.write(payload)
        os.replace(temp, path)
    except BaseException:
        if os.path.exists(temp):
            os.unlink(temp)
        raise


def _restore(written: list, backup: Path) -> None:
    for path, key, relative in reversed(written):
        saved = backup / key / relative
        if saved.is_file():
            _atomic_write(path, saved.read_bytes())
        elif path.is_file():
            path.unlink()


def apply(items: list, roots: dict, backup: Path, partial: bool) -> list:
    """Write planned changes; restore every touched file on any failure."""
    blocked = [item for item in items if item.status in BLOCKERS]
    if blocked and not partial:
        raise RuntimeError("%d conflict/error item(s); resolve them or pass --partial" % len(blocked))
    written = []
    try:
        for item in (item for item in items if item.status in WRITES):
            path = Path(roots[item.target.root]) / item.target.relative
            if path.is_file():
                saved = backup / item.target.root / item.target.relative
                saved.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(str(path), str(saved))
            written.append((path, item.target.root, item.target.relative))
            if item.status == "DELETE":
                path.unlink()
            else:
                _atomic_write(path, encode(item.result, item.style))
    except BaseException:
        _restore(written, backup)
        raise
    for item in blocked:
        if isinstance(item.result, str):
            preview = backup / "conflicts" / item.target.root / (item.target.relative + ".conflict")
            _atomic_write(preview, item.result.encode("utf-8"))
    return [str(path) for path, _, _ in written]


def export_skill_delta(repository: Path, base: str, head: str, backup: Path) -> None:
    """Export the rendered public SKILL.md delta for manual canonical review."""
    diff = _git(repository, "diff", base, head, "--", SKILL_ENTRY).stdout
    if diff:
        _atomic_write(backup / "SKILL.public-delta.diff", diff)
        current = blob(repository, head, SKILL_ENTRY) or ""
        _atomic_write(backup / "SKILL.public-head.md", current.encode("utf-8"))


def print_report(items: list) -> None:
    order = {name: index for index, name in enumerate(BLOCKERS + WRITES + ("ALREADY_APPLIED", "SKIPPED"))}
    for item in sorted(items, key=lambda value: (order.get(value.status, 99), value.sources)):
        destination = "%s:%s" % (item.target.root, item.target.relative) if item.target.root else "-"
        print("%-15s %-58s -> %s" % (item.status, ", ".join(item.sources), destination))
        if item.detail:
            print(" " * 16 + item.detail)
    counts: dict = {}
    for item in items:
        counts[item.status] = counts.get(item.status, 0) + 1
    print("SUMMARY " + ", ".join("%s=%d" % pair for pair in sorted(counts.items())))


def _preflight(repository: Path, canonical: Path, refs: tuple) -> str:
    """Return a blocking problem, or an empty string when inputs are sane."""
    if not (canonical / "SKILL.md").is_file() or not (canonical / "workflow_contract.json").is_file():
        return "not a canonical video-autopilot skill (SKILL.md + workflow_contract.json): %s" % canonical
    try:
        canonical.relative_to(repository)
    except ValueError:
        pass
    else:
        return "--canonical points inside the public repository; use the private skill copy"
    for ref in refs:
        if _git(repository, "rev-parse", "--verify", "--quiet", ref + "^{commit}", check=False).returncode:
            return "unknown commit: %s" % ref
    return ""


def _roots(args) -> dict:
    roots = {"canonical": args.canonical}
    if args.cleanup_helper:
        roots["cleanup"] = args.cleanup_helper
    if args.workspace:
        roots["workspace"] = args.workspace
    return {key: Path(value).expanduser().resolve() for key, value in roots.items()}


def run(args) -> int:
    repository = Path(args.repository).resolve()
    roots = _roots(args)
    problem = _preflight(repository, roots["canonical"], (args.base, args.head))
    if problem:
        print("BACKPORT BLOCKED: " + problem)
        return 2
    items = replay(repository, args.base, args.head, roots)
    print_report(items)
    if args.report:
        payload = {"base": args.base, "head": args.head, "items": [item.row() for item in items]}
        _atomic_write(Path(args.report), (json.dumps(payload, ensure_ascii=False, indent=2) + "\n").encode("utf-8"))
    blocked = any(item.status in BLOCKERS for item in items)
    if not args.apply:
        print("DRY RUN: nothing written. Re-run with --apply to write the canonical files.")
        return 1 if blocked else 0
    stamp = time.strftime("%Y%m%d-%H%M%S")
    backup = Path(args.backup_dir or repository / ".video-autopilot" / "backport" / stamp).resolve()
    try:
        written = apply(items, roots, backup, args.partial)
    except RuntimeError as exc:
        print("APPLY REFUSED: %s" % exc)
        return 1
    export_skill_delta(repository, args.base, args.head, backup)
    print("APPLIED %d file(s); backups and conflict previews: %s" % (len(written), backup))
    print("NEXT: python scripts/sync_canonical.py --canonical \"%s\"  then  git status" % roots["canonical"])
    print("      An exact backport leaves only sync-receipt.json modified.")
    return 1 if blocked else 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--canonical", help="private canonical skill root (contains SKILL.md)")
