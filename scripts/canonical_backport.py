#!/usr/bin/env python3
"""Backport public-kit edits into the private canonical Video Autopilot skill.

``sync_canonical.py`` publishes the canonical skill through privacy transforms,
so an edit made only in the public kit is overwritten by the next sync.  This
tool replays the public delta between two commits onto the canonical files with
a three-way merge (``git merge-file``).  Canonical-only text that the public
transforms removed or rewrote is kept; overlapping edits become conflicts
instead of silent replacements.

Dry-run is the default.  ``--apply`` is all-or-nothing unless ``--partial`` is
given; it backs up every touched canonical file, writes atomically, keeps the
canonical BOM and line endings, and never writes a conflicted merge.  After an
apply, re-run ``sync_canonical.py --canonical <dir>``: when the backport is
exact, ``git status`` shows only ``sync-receipt.json`` (new canonical hashes).
"""
